#!/usr/bin/env node
// Embeds public/splash-screen.svg into a TS module so native can render it (with its CSS animation) in a WebView.
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const svg = fs.readFileSync(path.join(root, 'public/splash-screen.svg'), 'utf8');
const out = path.join(root, 'src/assets/splashSvg.ts');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  `// Generated by scripts/sync-splash-svg.js from public/splash-screen.svg. Do not edit.\nexport const SPLASH_SVG = ${JSON.stringify(svg)};\n`,
);
console.log(`Wrote ${path.relative(root, out)}`);
